function flow(name: string, pitch: string, hook: string, protagonistGoal: string, obstacle: string, readingExperience: string, audience: string): SubGenre {
  return { name, pitch, hook, protagonistGoal, obstacle, readingExperience, audience };
}

export function genreLabel(category: string, flowName: string): string {
  return `${category}·${flowName}`.slice(0, 50);
}

/** Matches a hot theme name to a sub-genre in the catalog, if any. */
export function findFlow(theme: string): { category: GenreCategory; flow: SubGenre } | undefined {
  for (const category of GENRES) {
    const found = category.flows.find((item) => item.name === theme
      || item.name.replace(/流$/, '') === theme
      || (theme.length >= 3 && (item.name.includes(theme) || theme.includes(item.name))));
    if (found) return { category, flow: found };
  }
  return undefined;
}
